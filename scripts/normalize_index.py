def sortkey(k):
    s = k.lstrip('#').lower().replace('ё', 'е')
    s = re.sub(r'^[«"\'(]+', '', s)
    return s

def render(k):
    segs = []
    for lec in sorted(data[k]):
        d = data[k][lec]
        s = f"Л{lec} " + ', '.join(f'[{r}]' for r in sorted(d['refs']))
        if d['gl']: s += ' — ' + ', '.join(d['gl'])
        segs.append(s)
    line = f"- **{k.lstrip('#')}** — " + '; '.join(segs)
    if works.get(k):
        ws = sorted(works[k].items(), key=lambda kv: min(kv[1]))
        line += '. Труды: ' + '; '.join(f"{wk} — " + ', '.join(f'Л{l}' for l in sorted(ls)) for wk, ls in ws)
    return line

