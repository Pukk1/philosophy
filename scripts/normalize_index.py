SEG = re.compile(r'^Л(\d+) ((?:\[\d\d:\d\d:\d\d\](?:, )?)+)(?: — (.*))?$')
TC = re.compile(r'\[(\d\d:\d\d:\d\d)\]')

def parse_body(body):
    parts = re.split(r'\.?; (?=Л\d+ \[)', body)
    out = []
    for p in parts:
        m = SEG.match(p.strip())
        assert m, ('bad seg', p)
        out.append((int(m.group(1)), TC.findall(m.group(2)), (m.group(3) or '').rstrip('.').strip()))
    return out

ENTRY = re.compile(r'^- \*\*(.+?)\*\* — (.*)$')
def parse_line(i):
    m = ENTRY.match(lines[i-1]); assert m, (i, lines[i-1])
    return parse_body(m.group(2))

def clean(g): return g.replace('; ', ', ').strip()

